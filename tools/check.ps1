# One-shot check before pushing: Blink, sourcemap, luau-lsp types, Selene, StyLua, Rojo build.
# A step whose tool is missing is skipped with a note. Exits 1 if any step failed.
$ErrorActionPreference = "Continue"
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

if ($env:USERPROFILE) {
  $RokitBin = Join-Path $env:USERPROFILE ".rokit\bin"
  if (Test-Path -LiteralPath $RokitBin) {
    $env:Path = "$RokitBin;$env:Path"
  }
}

# Roblox API types for luau-lsp. Delete the file to fetch a fresh copy.
$DefsDir = Join-Path $Root ".cache\luau-lsp"
$Defs = Join-Path $DefsDir "globalTypes.None.d.luau"
$DefsUrls = @(
  "https://raw.githubusercontent.com/JohnnyMorganz/luau-lsp/main/scripts/globalTypes.None.d.luau",
  "https://luau-lsp.pages.dev/type-definitions/globalTypes.None.d.luau"
)

# Generated by Blink; checked through events.blink instead.
$Generated = @("src/shared/events", "src/server/events")

$script:Summary = New-Object System.Collections.Generic.List[string]
$script:Failed = $false

function Pass([string]$Name) { $script:Summary.Add("ok    $Name") }
function Fail([string]$Name) { $script:Summary.Add("FAIL  $Name"); $script:Failed = $true }
function Skip([string]$Name, [string]$Why) { $script:Summary.Add("skip  $Name ($Why)") }

function Step([string]$Name) {
  Write-Host ""
  Write-Host "== $Name"
}

function Find-Tool([string]$Name) {
  $cmd = Get-Command $Name -ErrorAction SilentlyContinue
  if ($cmd) { return $cmd.Source }
  return $null
}

function Get-Defs {
  if ((Test-Path -LiteralPath $Defs) -and (Get-Item -LiteralPath $Defs).Length -gt 0) { return $true }
  New-Item -ItemType Directory -Force -Path $DefsDir | Out-Null
  # Windows PowerShell 5.1 may default to TLS 1.0.
  [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
  $tmp = "$Defs.tmp"
  foreach ($url in $DefsUrls) {
    Write-Host "downloading $url"
    try {
      Invoke-WebRequest -Uri $url -OutFile $tmp -UseBasicParsing -ErrorAction Stop
      if ((Get-Item -LiteralPath $tmp).Length -gt 0) {
        Move-Item -LiteralPath $tmp -Destination $Defs -Force
        return $true
      }
    } catch {
      Write-Host "  failed: $($_.Exception.Message)"
    }
  }
  Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue
  return $false
}

# luau-lsp 1.56.0 started requiring named definition files (--definitions:@roblox=PATH).
function Get-DefsFlag([string]$LuauLsp) {
  $version = (& $LuauLsp --version 2>$null | Select-Object -First 1)
  if ("$version" -match '(\d+)\.(\d+)') {
    $major = [int]$Matches[1]
    $minor = [int]$Matches[2]
    if ($major -eq 1 -and $minor -lt 56) { return "--definitions=$Defs" }
    if ($major -lt 1) { return "--definitions=$Defs" }
  }
  return "--definitions:@roblox=$Defs"
}

$blink = Find-Tool "blink"
$rojo = Find-Tool "rojo"
$wally = Find-Tool "wally"
$packageTypes = Find-Tool "wally-package-types"
$luauLsp = Find-Tool "luau-lsp"
$selene = Find-Tool "selene"
$stylua = Find-Tool "stylua"

Step "blink"
if ($null -eq $blink) {
  Skip "blink" "blink not found"
} else {
  $out = & $blink events.blink 2>&1
  if ($LASTEXITCODE -eq 0) { Pass "blink" } else { $out | ForEach-Object { Write-Host $_ }; Fail "blink" }
}

$installedPackages = $false
Step "packages"
if (Test-Path -LiteralPath (Join-Path $Root "Packages")) {
  Write-Host "Packages present"
  Pass "packages"
} elseif ($null -eq $wally) {
  Skip "packages" "no Packages folder and wally not found"
} else {
  & $wally install
  if ($LASTEXITCODE -eq 0) { $installedPackages = $true; Pass "packages (wally install)" } else { Fail "packages (wally install)" }
}

Step "sourcemap"
if ($null -eq $rojo) {
  Skip "sourcemap" "rojo not found"
} else {
  & $rojo sourcemap default.project.json -o sourcemap.json
  if ($LASTEXITCODE -eq 0) {
    Pass "sourcemap"
    if ($installedPackages -and $packageTypes) {
      # Packages were just installed: give the thunks their types, then refresh the map.
      & $packageTypes --sourcemap sourcemap.json Packages/ *> $null
      if ($LASTEXITCODE -ne 0) { Write-Host "wally-package-types reported errors" }
      & $rojo sourcemap default.project.json -o sourcemap.json *> $null
    }
  } else {
    Fail "sourcemap"
  }
}

Step "luau-lsp analyze"
if ($null -eq $luauLsp) {
  Skip "luau-lsp" "luau-lsp not found"
} elseif (-not (Get-Defs)) {
  Skip "luau-lsp" "could not download Roblox definitions"
} else {
  $lspArgs = @("analyze", (Get-DefsFlag $luauLsp), "--sourcemap=sourcemap.json", "--ignore=Packages/**")
  foreach ($dir in $Generated) { $lspArgs += "--ignore=$dir/**" }
  $lspArgs += "src"
  & $luauLsp @lspArgs
  if ($LASTEXITCODE -eq 0) { Pass "luau-lsp" } else { Fail "luau-lsp" }
}

Step "selene"
if ($null -eq $selene) {
  Skip "selene" "selene not found"
} else {
  & $selene src
  if ($LASTEXITCODE -eq 0) { Pass "selene" } else { Fail "selene" }
}

Step "stylua"
if ($null -eq $stylua) {
  Skip "stylua" "stylua not found"
} else {
  & $stylua --check src
  if ($LASTEXITCODE -eq 0) { Pass "stylua" } else { Fail "stylua (run: stylua src)" }
}

Step "rojo build"
if ($null -eq $rojo) {
  Skip "rojo build" "rojo not found"
} else {
  New-Item -ItemType Directory -Force -Path (Join-Path $Root "build") | Out-Null
  & $rojo build default.project.json -o build/check.rbxlx
  if ($LASTEXITCODE -eq 0) { Pass "rojo build" } else { Fail "rojo build" }
}

Write-Host ""
Write-Host "== summary"
$script:Summary | ForEach-Object { Write-Host $_ }
if ($script:Failed) { exit 1 }
exit 0
