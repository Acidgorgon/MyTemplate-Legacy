#!/usr/bin/env bash
# One-shot check before pushing: Blink, sourcemap, luau-lsp types, Selene, StyLua, Rojo build.
# A step whose tool is missing is skipped with a note. Exits 1 if any step failed.
# bash 3.2 compatible (macOS /bin/bash).
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

if [ -d "$HOME/.rokit/bin" ]; then
  export PATH="$HOME/.rokit/bin:$PATH"
fi

# Roblox API types for luau-lsp. Delete the file to fetch a fresh copy.
DEFS_DIR="$ROOT/.cache/luau-lsp"
DEFS="$DEFS_DIR/globalTypes.None.d.luau"
DEFS_URLS="https://raw.githubusercontent.com/JohnnyMorganz/luau-lsp/main/scripts/globalTypes.None.d.luau
https://luau-lsp.pages.dev/type-definitions/globalTypes.None.d.luau"

# Generated by Blink; checked through events.blink instead.
GENERATED="src/shared/events src/server/events"

summary=""
failed=0

record() {
  summary="$summary$1
"
}
pass() { record "ok    $1"; }
fail() { record "FAIL  $1"; failed=1; }
skip() { record "skip  $1 ($2)"; }

step() {
  echo
  echo "== $1"
}

find_tool() {
  command -v "$1" 2>/dev/null || true
}

download() {
  local url="$1" out="$2"
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL -o "$out" "$url"
  elif command -v wget >/dev/null 2>&1; then
    wget -q -O "$out" "$url"
  else
    return 1
  fi
}

fetch_defs() {
  [ -s "$DEFS" ] && return 0
  mkdir -p "$DEFS_DIR"
  local url
  while IFS= read -r url; do
    [ -n "$url" ] || continue
    echo "downloading $url"
    if download "$url" "$DEFS.tmp" && [ -s "$DEFS.tmp" ]; then
      mv "$DEFS.tmp" "$DEFS"
      return 0
    fi
  done <<EOF
$DEFS_URLS
EOF
  rm -f "$DEFS.tmp"
  return 1
}

# luau-lsp 1.56.0 started requiring named definition files (--definitions:@roblox=PATH).
defs_flag() {
  local version major minor
  version="$("$1" --version 2>/dev/null | head -n 1)"
  major="$(printf '%s' "$version" | sed -E 's/^[^0-9]*([0-9]+)\.([0-9]+).*$/\1/')"
  minor="$(printf '%s' "$version" | sed -E 's/^[^0-9]*([0-9]+)\.([0-9]+).*$/\2/')"
  case "$major$minor" in
    *[!0-9]*|"") major=1; minor=56 ;;
  esac
  if [ "$major" -gt 1 ] || { [ "$major" -eq 1 ] && [ "$minor" -ge 56 ]; }; then
    printf '%s' "--definitions:@roblox=$DEFS"
  else
    printf '%s' "--definitions=$DEFS"
  fi
}

blink="$(find_tool blink)"
rojo="$(find_tool rojo)"
wally="$(find_tool wally)"
package_types="$(find_tool wally-package-types)"
luau_lsp="$(find_tool luau-lsp)"
selene="$(find_tool selene)"
stylua="$(find_tool stylua)"

step "blink"
if [ -z "$blink" ]; then
  skip "blink" "blink not found"
else
  if out="$("$blink" events.blink 2>&1)"; then
    pass "blink"
  else
    printf '%s\n' "$out"
    fail "blink"
  fi
fi

installed_packages=0
step "packages"
if [ -d "$ROOT/Packages" ]; then
  echo "Packages present"
  pass "packages"
elif [ -z "$wally" ]; then
  skip "packages" "no Packages folder and wally not found"
elif "$wally" install; then
  installed_packages=1
  pass "packages (wally install)"
else
  fail "packages (wally install)"
fi

step "sourcemap"
if [ -z "$rojo" ]; then
  skip "sourcemap" "rojo not found"
elif "$rojo" sourcemap default.project.json -o sourcemap.json; then
  pass "sourcemap"
  if [ "$installed_packages" -eq 1 ] && [ -n "$package_types" ]; then
    # Packages were just installed: give the thunks their types, then refresh the map.
    "$package_types" --sourcemap sourcemap.json Packages/ >/dev/null 2>&1 || echo "wally-package-types reported errors"
    "$rojo" sourcemap default.project.json -o sourcemap.json >/dev/null 2>&1
  fi
else
  fail "sourcemap"
fi

step "luau-lsp analyze"
if [ -z "$luau_lsp" ]; then
  skip "luau-lsp" "luau-lsp not found"
elif ! fetch_defs; then
  skip "luau-lsp" "could not download Roblox definitions"
else
  set -- analyze "$(defs_flag "$luau_lsp")" --sourcemap=sourcemap.json --ignore="Packages/**"
  for dir in $GENERATED; do
    set -- "$@" --ignore="$dir/**"
  done
  if "$luau_lsp" "$@" src; then
    pass "luau-lsp"
  else
    fail "luau-lsp"
  fi
fi

step "selene"
if [ -z "$selene" ]; then
  skip "selene" "selene not found"
elif "$selene" src; then
  pass "selene"
else
  fail "selene"
fi

step "stylua"
if [ -z "$stylua" ]; then
  skip "stylua" "stylua not found"
elif "$stylua" --check src; then
  pass "stylua"
else
  fail "stylua (run: stylua src)"
fi

step "rojo build"
if [ -z "$rojo" ]; then
  skip "rojo build" "rojo not found"
else
  mkdir -p build
  if "$rojo" build default.project.json -o build/check.rbxlx; then
    pass "rojo build"
  else
    fail "rojo build"
  fi
fi

echo
echo "== summary"
printf '%s' "$summary"
exit "$failed"
